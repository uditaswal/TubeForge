"""Download the Latin subset of IBM Plex Sans and IBM Plex Mono into src/tubeforge/assets/ui/fonts/.

Writes src/tubeforge/assets/ui/fonts.css with @font-face rules that point at the local files, so the dashboard
does not load fonts from Google at run time. Re-run only when the font versions change; the output is committed.
License: SIL Open Font License 1.1 (IBM Plex).
"""

from __future__ import annotations

import re
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "src" / "tubeforge" / "assets" / "ui"
FAMILIES = [
    ("IBM Plex Sans", "IBM+Plex+Sans:wght@400;500;600"),
    ("IBM Plex Mono", "IBM+Plex+Mono:wght@400;500"),
]
UA = {"User-Agent": "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120 Safari/537.36"}


def fetch(url: str) -> bytes:
    with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=60) as response:
        return response.read()


def main() -> None:
    import hashlib

    (OUT / "fonts").mkdir(parents=True, exist_ok=True)
    rules: list[str] = []
    for family, query in FAMILIES:
        css = fetch(f"https://fonts.googleapis.com/css2?family={query}&display=swap").decode()
        faces: dict[str, dict] = {}  # file content hash -> {"weights": [...], "bytes": ..., "name": ...}
        for block in re.findall(r"/\* latin \*/\s*(@font-face\s*\{.*?\})", css, re.S):
            weight = int(re.search(r"font-weight:\s*(\d+)", block).group(1))
            url = re.search(r"url\((https://[^)]+\.woff2)\)", block).group(1)
            data = fetch(url)
            key = hashlib.sha256(data).hexdigest()[:16]
            entry = faces.setdefault(key, {"weights": [], "bytes": data})
            entry["weights"].append(weight)
        slug = family.lower().replace(" ", "-")
        for key, entry in faces.items():
            weights = sorted(entry["weights"])
            # One file with several weights is a variable font: declare the range, not one face per weight.
            variable = len(weights) > 1
            filename = f"{slug}-{key}.woff2" if variable else f"{slug}-{weights[0]}.woff2"
            (OUT / "fonts" / filename).write_bytes(entry["bytes"])
            weight_css = f"{weights[0]} {weights[-1]}" if variable else str(weights[0])
            rules.append(
                "@font-face {\n"
                f"  font-family: '{family}';\n"
                "  font-style: normal;\n"
                f"  font-weight: {weight_css};\n"
                "  font-display: swap;\n"
                f"  src: url('fonts/{filename}') format('woff2');\n"
                "}"
            )
            print("fetched", filename, "weights", weights)
    header = "/* IBM Plex (SIL Open Font License 1.1). Latin subset, served from /static/ui/fonts/. Generated by scripts/fetch_design_fonts.py. */\n"
    stale = [f for f in (OUT / "fonts").glob("*.woff2")]
    keep = {line.split("url('fonts/")[1].split("'")[0] for line in "\n".join(rules).splitlines() if "url('fonts/" in line}
    for f in stale:
        if f.name not in keep:
            f.unlink()
    (OUT / "fonts.css").write_text(header + "\n".join(rules) + "\n")
    print("wrote fonts.css with", len(rules), "faces")


if __name__ == "__main__":
    main()
